// WWE 2K16 native renderer: the player's own game shaders, converted on the player's PC.
//
// No game-derived data ships with the port (decision of 2026-10-27), so the executable links no
// generated shader cache. When the game creates a shader (D3DDevice_CreateVertex/PixelShader,
// re:Blue's CreateShader), a container this cache does not know is converted in the background:
// XenosRecomp's translator (built in, MIT) writes HLSL, DXC (dxcompiler.dll beside the exe) turns
// it into SPIR-V, smol-v packs it. Each result is appended to cache/native_shaders.bin next to the
// executable, so only the first launch converts (about 600 shaders, all created at boot). Until a
// shader is ready, re:Blue finds no entry for it and skips the draws that need it: nothing
// crashes, the picture fills in as conversions finish. The cache file is never shipped.

