ShaderCacheEntry *Wwe2k16FindShaderEntry(uint64_t hash) {
  std::call_once(g_load_once, LoadCacheFile);
  std::shared_lock lock(g_entries_mutex);
  auto it = g_entries.find(hash);
  return it == g_entries.end() ? nullptr : &it->second->entry;
}

const uint8_t *Wwe2k16ShaderSpirv(const ShaderCacheEntry *entry) {
  if (!entry)
    return nullptr;
  std::shared_lock lock(g_entries_mutex);
  auto it = g_entries.find(entry->hash);
  return it == g_entries.end() ? nullptr : it->second->smolv.data();
}

bool Wwe2k16DxcUsable() {
  if (!LoadDxc())  // logs "missing or unusable"
    return false;
  IDxcCompiler3 *dxc = nullptr;
  if (FAILED(g_dxc_create(CLSID_DxcCompiler, IID_PPV_ARGS(&dxc))) || !dxc) {
    BD_ERROR("Native shaders: dxcompiler.dll loaded but its compiler instance can't be created: "
             "the game's shaders can't be converted");
    return false;
  }
  dxc->Release();
  return true;
}

void Wwe2k16WaitShader(bd::gpu::GuestShader *shader, uint32_t timeout_ms) {
  if (!shader)
    return;
  std::unique_lock lock(g_jobs_mutex);
  const auto pending = [shader] {
    for (const auto &[hash, shaders] : g_waiting)
      for (const auto *s : shaders)
        if (s == shader)
          return true;
    return false;
  };
  if (shader->shaderCacheEntry || !pending())
    return;
  // Convert it next: at first launch hundreds of shaders are queued ahead of it.
  for (auto &[hash, shaders] : g_waiting) {
    if (std::find(shaders.begin(), shaders.end(), shader) == shaders.end())
      continue;
    auto job = std::find_if(g_jobs.begin(), g_jobs.end(), [h = hash](const Job &j) { return j.hash == h; });
    if (job != g_jobs.end() && job != g_jobs.begin()) {
      Job moved = std::move(*job);
      g_jobs.erase(job);
      g_jobs.push_front(std::move(moved));
    }
    break;
  }
  const auto start = std::chrono::steady_clock::now();
  g_published_cv.wait_for(lock, std::chrono::milliseconds(timeout_ms),
                          [&] { return shader->shaderCacheEntry || !pending(); });
  static std::atomic<uint32_t> s_logged{0};
  if (s_logged.fetch_add(1) < 20)
    BD_INFO("Native shaders: a draw waited {} ms for its shader ({})",
            std::chrono::duration_cast<std::chrono::milliseconds>(
                std::chrono::steady_clock::now() - start).count(),
            shader->shaderCacheEntry ? "ready" : "not ready, skipped");
}

void Wwe2k16RequestShader(uint64_t hash, const uint8_t *container, uint32_t size,
                          bd::gpu::GuestShader *shader) {
  if (!container || size < 0x24 || size > (1u << 20))
    return;
  {
    std::lock_guard lock(g_jobs_mutex);
    if (g_failed.count(hash))
      return;
    auto [it, first] = g_waiting.try_emplace(hash);
    it->second.push_back(shader);
    if (!first)
      return;  // already queued: this GuestShader gets the entry with the first one
    if (!g_queued.load())
      g_first_request = std::chrono::steady_clock::now();
  }
  // A conversion may have finished between the caller's lookup and this request.
  if (Wwe2k16FindShaderEntry(hash)) {
    Publish(hash);
    return;
  }
  if (!LoadDxc())
    return;
  const bool pixel = (container[3] & 1) == 0;  // flags 0x102A11xx, bit 0 set = vertex shader
  {
    std::lock_guard lock(g_jobs_mutex);
    g_jobs.push_back(Job{hash, pixel, std::vector<uint8_t>(container, container + size)});
    ++g_queued;
  }
  StartWorkers();
  g_jobs_cv.notify_one();
}
