"""Writes a functions_thunks.toml: functions reached only through pointers built at run time.

Two kinds, each a standalone function right after blr / bctr / padding:
  * vtable thunks: lwz rA,0(r3); lwz rB,N(rA); mtctr rB; bctr
  * short straight-line code (<= 8 instructions) ending in mtctr; bctr (argument-shuffling thunks, call trampolines
    such as an APC routine)
Left out (each of these broke the game when included): registered functions, addresses that are `loc_` labels in the
generated code, addresses inside a .pdata function, padding words, overlaps, and the import stubs from 0x83380000.

Run it on a generation made WITHOUT a thunks file, so the labels are those of the real functions:
    python -I tools/scan_thunks.py work/image_tu.bin generated_tu config_tu/functions_thunks.toml
"""
import bisect
import glob
import importlib.util
import os
import re
import struct
import sys

image_path, generated, out_path = sys.argv[1:4]
data = open(image_path, "rb").read()
BASE, IMPORTS = 0x82000000, 0x83380000
BLR, BCTR = 0x4E800020, 0x4E800420

spec = importlib.util.spec_from_file_location("ff", os.path.join(os.path.dirname(__file__), "find_functions.py"))
ff = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ff)
img = ff.Image(data, BASE)
starts = sorted(img.pdata)


def word(a):
    return struct.unpack_from(">I", data, a - BASE)[0]


def inside_pdata(a):
    i = bisect.bisect_right(starts, a) - 1
    return i >= 0 and starts[i] <= a < starts[i] + img.pdata[starts[i]]


registered, labels = set(), set()
for path in glob.glob(os.path.join(generated, "*.h")) + glob.glob(os.path.join(generated, "*.cpp")):
    text = open(path, errors="replace").read()
    registered.update(int(x, 16) for x in re.findall(r"sub_([0-9A-F]{8})", text))
    labels.update(int(x, 16) for x in re.findall(r"loc_([0-9A-F]{8}):", text))

found, last = [], 0
for lo, hi in img.code:
    for a in range(lo + 4, min(hi, IMPORTS) - 8, 4):
        if word(a - 4) not in (BLR, BCTR, 0) or word(a) == 0 or a < last:
            continue
        if a in registered or a in labels or inside_pdata(a):
            continue
        end = None
        for n in range(2, 9):
            w = word(a + 4 * (n - 1))
            if w == BCTR:
                if (word(a + 4 * (n - 2)) & 0xFC1FFFFF) == 0x7C0903A6:  # mtctr rX
                    end = a + 4 * n
                break
            if (w >> 26) in (16, 18, 19):  # branch, blr, CR ops
                break
        if end:
            found.append((a, end - a))
            last = end

with open(out_path, "w", encoding="utf-8") as f:
    f.write(__doc__.split("\n\n")[1].replace("\n", "\n# ").join(["# ", "\n"]))
    f.write(f"# Generated by tools/scan_thunks.py from {os.path.basename(image_path)}.\n\n[functions]\n")
    for a, size in found:
        f.write(f"0x{a:08X} = {{ size = 0x{size:X} }}\n")
print(f"{len(found)} thunks")
